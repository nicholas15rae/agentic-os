//! Cross-device companion approval: the desktop (no biometrics) asks the paired phone to approve
//! an unlock with its fingerprint.
//!
//! 1. Desktop Rust posts `{id, nonce, device, purpose, expiresAt}` to the gateway mailbox
//!    (`POST /api/security/companion/request`, loopback only). The nonce never leaves Rust
//!    except to the gateway.
//! 2. The phone app polls `GET /api/security/companion/pending`, shows the request, runs its own
//!    biometric check (Rust, `tauri-plugin-biometric`) and signs
//!    `hmac(pairKey, "approve|id|nonce|deviceId")` → `POST /api/security/companion/respond`.
//! 3. Desktop Rust polls `GET /api/security/companion/result/{id}` and verifies the signature
//!    with ITS copy of the pairing key. The gateway is only a mailbox: it can't forge approval.
//!
//! The pairing key is generated by `gabagool-cli pair-companion` (desktop keychain) and entered
//! once on the phone (Settings → Security → companion pairing), or shown as a pairing QR. A QR key
//! is only PENDING on the desktop (`pair_begin_qr`): it becomes the active pairing key on the
//! first approval the phone signs with it within `PAIR_QR_TTL_S` (`verify_approval`), and is
//! bound to that phone; unconfirmed, it is discarded at expiry and the previous pairing stays.

use std::collections::HashMap;
use std::path::Path;
use std::sync::Mutex;
use std::time::Duration;

const PAIR_ACCOUNT: &str = "companion-pair@security";
const PAIR_FILE: &str = "companion.key";
const DEVICE_ACCOUNT: &str = "companion-device@security";
const DEVICE_FILE: &str = "companion-device.key";

fn load_key(account: &str, dir: &Path, file: &str) -> Option<Vec<u8>> {
    let v = super::keychain(account).and_then(|e| e.get_password().ok()).or_else(|| std::fs::read_to_string(dir.join(file)).ok())?;
    super::unhex(v.trim()).filter(|k| k.len() >= 16)
}

fn store_key(account: &str, dir: &Path, file: &str, hexkey: &str) -> Result<&'static str, String> {
    if super::unhex(hexkey).is_none_or(|k| k.len() < 16) {
        return Err("the pairing key must be at least 32 hex characters".into());
    }
    if let Some(e) = super::keychain(account) {
        if e.set_password(hexkey).is_ok() && e.get_password().ok().as_deref() == Some(hexkey) {
            let _ = std::fs::remove_file(dir.join(file));
            return Ok("keychain");
        }
    }
    super::shared::write_atomic(&dir.join(file), hexkey.as_bytes()).map_err(|e| e.to_string())?;
    Ok("file")
}

/// Desktop side: the key that verifies phone approvals.
pub fn pair_key(dir: &Path) -> Option<Vec<u8>> {
    load_key(PAIR_ACCOUNT, dir, PAIR_FILE)
}

/// Non-secret: the phone device id a QR pairing was confirmed by (`verify_approval`). Only that
/// phone's approvals count for the active key; the CLI pairing removes it (any device, as before).
const BOUND_FILE: &str = "companion.bound";

fn bound_device(dir: &Path) -> Option<String> {
    std::fs::read_to_string(dir.join(BOUND_FILE)).ok().map(|s| s.trim().to_string()).filter(|s| !s.is_empty())
}

fn mark_paired(dir: &Path) {
    // Non-secret marker for the gateway (it can't read the keychain): "a phone is paired, queue
    // alerts for it".
    let _ = super::shared::write_atomic(&dir.join("companion.paired"), format!("{}
", super::now() as u64).as_bytes());
}

/// Generate a new pairing key on the desktop (CLI); returns it (hex) to enter on the phone. Active
/// at once, for any device (no QR pending / binding involved).
pub fn pair_generate(dir: &Path) -> Result<String, String> {
    let k = super::token::random_hex(32);
    store_key(PAIR_ACCOUNT, dir, PAIR_FILE, &k)?;
    let _ = std::fs::remove_file(dir.join(BOUND_FILE));
    mark_paired(dir);
    Ok(k)
}

/// A QR pairing key the desktop has shown but no phone has used yet (process memory only: the
/// approval that confirms it is verified by this same process; a restart just drops it).
#[derive(Clone, Debug, PartialEq)]
pub struct PendingPair {
    pub key: Vec<u8>,
    pub expires_at: f64,
}

static PAIR_PENDING: Mutex<Option<PendingPair>> = Mutex::new(None);

/// Desktop: a NEW pairing key for a QR, stored as PENDING until `expires_at` (replacing any older
/// pending one). The active pairing (if any) is untouched until the phone uses the new key.
/// Returns `(key hex, expires_at)`.
pub fn pair_begin_qr(now: f64) -> (String, f64) {
    let k = super::token::random_hex(32);
    let expires_at = now + PAIR_QR_TTL_S;
    let key = super::unhex(&k).unwrap_or_default();
    *PAIR_PENDING.lock().unwrap_or_else(|p| p.into_inner()) = Some(PendingPair { key, expires_at });
    (k, expires_at)
}

/// The pending QR key, if it is still within its TTL; an expired one is discarded here.
fn pending_pair(now: f64) -> Option<PendingPair> {
    let mut g = PAIR_PENDING.lock().unwrap_or_else(|p| p.into_inner());
    if g.as_ref().is_some_and(|p| now > p.expires_at) {
        *g = None;
    }
    g.clone()
}

fn clear_pending() {
    *PAIR_PENDING.lock().unwrap_or_else(|p| p.into_inner()) = None;
}

/// Is there a pairing key an approval could be verified with (active, or a live pending QR)?
pub fn pairing_possible(dir: &Path) -> bool {
    pair_key(dir).is_some() || pending_pair(super::now()).is_some()
}

/// Which key verified an approval (`approval_verdict`).
#[derive(Debug, PartialEq)]
pub enum ApprovalKey {
    /// The active pairing key (and, for a QR pairing, the phone it is bound to).
    Active,
    /// The pending QR key, within its TTL: the first use. The caller makes it the active key,
    /// bound to this device.
    Promote,
}

/// The desktop's verdict on a signed approval (pure). `active`: the active pairing key; `bound`:
/// the phone a QR pairing is bound to (None: any device, the CLI pairing); `pending`: the QR key
/// shown last (expired or not). A pending key counts only within its TTL and only once (after it
/// is promoted, the same QR key is the active key bound to the first phone: another device
/// using that payload is refused). An expired, unused one never replaces the active pairing.
#[allow(clippy::too_many_arguments)]
pub fn approval_verdict(active: Option<&[u8]>, bound: Option<&str>, pending: Option<&PendingPair>, now: f64, id: &str, nonce: &str, device: &str, sig: &str) -> Result<ApprovalKey, String> {
    let ok = |k: &[u8]| super::token::companion_verify(k, id, nonce, device, sig);
    if active.is_some_and(|k| ok(k)) {
        if bound.is_some_and(|b| b != device) {
            return Err("COMPANION_OTHER_DEVICE: that pairing code was already used by another phone; show a new one on the desktop".into());
        }
        return Ok(ApprovalKey::Active);
    }
    if let Some(p) = pending.filter(|p| ok(&p.key)) {
        if now > p.expires_at {
            return Err("PAIR_QR_EXPIRED: that pairing code expired before it was used; show a new one on the desktop".into());
        }
        return Ok(ApprovalKey::Promote);
    }
    Err("COMPANION_BAD_SIGNATURE: the approval was not signed by the paired phone".into())
}

/// Desktop: check a phone approval's signature (`approval_verdict`), and on the first valid use
/// of a pending QR key make it the active pairing key, bound to `device`.
pub fn verify_approval(dir: &Path, id: &str, nonce: &str, device: &str, sig: &str) -> Result<(), String> {
    let now = super::now();
    let pending = PAIR_PENDING.lock().unwrap_or_else(|p| p.into_inner()).clone();
    let active = pair_key(dir);
    let verdict = approval_verdict(active.as_deref(), bound_device(dir).as_deref(), pending.as_ref(), now, id, nonce, device, sig);
    // An expired pending key is gone either way (the active pairing stays as it was).
    let _ = pending_pair(now);
    match verdict? {
        ApprovalKey::Active => Ok(()),
        ApprovalKey::Promote => {
            let p = pending.ok_or("COMPANION_BAD_SIGNATURE: no pending pairing")?;
            store_key(PAIR_ACCOUNT, dir, PAIR_FILE, &super::hex(&p.key))?;
            super::shared::write_atomic(&dir.join(BOUND_FILE), device.as_bytes()).map_err(|e| e.to_string())?;
            mark_paired(dir);
            clear_pending();
            Ok(())
        }
    }
}

/// How long a pairing QR stays valid (the phone refuses an older one).
pub const PAIR_QR_TTL_S: f64 = 120.0;
const PAIR_QR_PREFIX: &str = "gbgpair1|";

/// The QR text for a fresh pairing key (pure): `gbgpair1|<key hex>|<expires unix s>|<desktop id>`.
pub fn pair_payload(key_hex: &str, expires_at: f64, desktop: &str) -> String {
    format!("{PAIR_QR_PREFIX}{key_hex}|{}|{desktop}", expires_at.floor() as u64)
}

/// Phone side: what the pairing box (or a QR scan) holds → the key to store (pure). A plain hex key
/// (from `gabagool-cli pair-companion`) passes through; a QR payload must not be expired. Returns
/// the key and, for a QR, the desktop it came from.
pub fn parse_pair_input(input: &str, now: f64) -> Result<(String, Option<String>), String> {
    let t = input.trim();
    let Some(rest) = t.strip_prefix(PAIR_QR_PREFIX) else { return Ok((t.to_string(), None)) };
    let mut parts = rest.splitn(3, '|');
    let (key, exp, desktop) = (parts.next().unwrap_or(""), parts.next().unwrap_or(""), parts.next().unwrap_or(""));
    let exp: f64 = exp.parse().map_err(|_| "PAIR_QR_BAD: that pairing code is damaged; show a new one on the desktop".to_string())?;
    if now > exp {
        return Err("PAIR_QR_EXPIRED: that pairing code has expired; show a new one on the desktop".into());
    }
    Ok((key.to_string(), Some(desktop.chars().take(80).collect())))
}

/// Phone side: the key it signs approvals with.
pub fn device_key(dir: &Path) -> Option<Vec<u8>> {
    load_key(DEVICE_ACCOUNT, dir, DEVICE_FILE)
}

pub fn device_store(dir: &Path, hexkey: &str) -> Result<&'static str, String> {
    store_key(DEVICE_ACCOUNT, dir, DEVICE_FILE, hexkey.trim())
}

#[derive(Clone, Debug)]
struct Pending {
    nonce: String,
    expires: f64,
    purpose: String,
}

static PENDING: Mutex<Option<HashMap<String, Pending>>> = Mutex::new(None);

fn client(timeout: Duration) -> Result<reqwest::Client, String> {
    reqwest::Client::builder().timeout(timeout).build().map_err(|e| e.to_string())
}

/// The phone polls the mailbox every 3 s while its app is open; older than this = not there.
pub const PHONE_SEEN_WITHIN_S: f64 = 30.0;

/// Can the companion path be used right now: enabled, paired, AND the phone itself checked the
/// gateway mailbox recently. The desktop reaching its own loopback gateway proves nothing about
/// the phone; counting that as "available" blocked the PIN-only fallback while the phone was
/// offline (PIN refused with SECOND_FACTOR_REQUIRED and no phone to approve: a deadlock).
pub async fn reachable(gateway: &str, dir: &Path, enabled: bool) -> bool {
    if !enabled || !pairing_possible(dir) {
        return false;
    }
    let Ok(c) = client(Duration::from_millis(1500)) else { return false };
    let Ok(r) = c.get(format!("{}/api/security/state", gateway.trim_end_matches('/'))).send().await else { return false };
    if !r.status().is_success() {
        return false;
    }
    let seen = r.json::<serde_json::Value>().await.ok().and_then(|v| v.get("companionSeenAt").and_then(|x| x.as_f64())).unwrap_or(0.0);
    phone_recent(seen, super::now())
}

/// `seen` = the gateway's `companionSeenAt` (0 = never since it started).
pub fn phone_recent(seen: f64, now: f64) -> bool {
    seen > 0.0 && now - seen <= PHONE_SEEN_WITHIN_S
}

/// Post a new approval request; returns `(id, expiresAt)`.
pub async fn request(gateway: &str, dir: &Path, device: &str, purpose: &str, ttl: f64) -> Result<(String, f64), String> {
    if !pairing_possible(dir) {
        return Err("COMPANION_UNPAIRED: run `gabagool-cli pair-companion` and enter the key on the phone".into());
    }
    let id = super::token::random_hex(12);
    let nonce = super::token::random_hex(16);
    let expires = super::now() + ttl;
    let body = serde_json::json!({ "id": id, "nonce": nonce, "device": device, "purpose": purpose, "expiresAt": expires });
    let r = client(Duration::from_secs(5))?
        .post(format!("{}/api/security/companion/request", gateway.trim_end_matches('/')))
        .json(&body)
        .send()
        .await
        .map_err(|_| "COMPANION_OFFLINE: the gateway mailbox is unreachable".to_string())?;
    if !r.status().is_success() {
        return Err(format!("COMPANION_OFFLINE: the gateway refused the request ({})", r.status()));
    }
    let mut g = PENDING.lock().unwrap_or_else(|p| p.into_inner());
    let m = g.get_or_insert_with(HashMap::new);
    let now = super::now();
    m.retain(|_, p| p.expires > now);
    m.insert(id.clone(), Pending { nonce, expires, purpose: purpose.to_string() });
    Ok((id, expires))
}

#[derive(Debug, PartialEq)]
pub enum PollState {
    Pending,
    /// `purpose` is what this process asked for ("unlock", "idle", "step_up:trading", ...).
    Approved { device: String, purpose: String },
    Denied,
    Expired,
}

/// The verdict on a request this process created (signature checked here).
pub async fn poll(gateway: &str, dir: &Path, id: &str) -> Result<PollState, String> {
    let pending = {
        let g = PENDING.lock().unwrap_or_else(|p| p.into_inner());
        g.as_ref().and_then(|m| m.get(id).cloned())
    };
    let Some(p) = pending else { return Ok(PollState::Expired) };
    if super::now() > p.expires {
        forget(id);
        return Ok(PollState::Expired);
    }
    let r = client(Duration::from_secs(5))?
        .get(format!("{}/api/security/companion/result/{}", gateway.trim_end_matches('/'), id))
        .send()
        .await
        .map_err(|_| "COMPANION_OFFLINE: the gateway mailbox is unreachable".to_string())?;
    let v: serde_json::Value = r.json().await.map_err(|e| e.to_string())?;
    match v["state"].as_str() {
        Some("approved") => {
            let device = v["deviceId"].as_str().unwrap_or("").to_string();
            let sig = v["sig"].as_str().unwrap_or("");
            forget(id);
            if device.is_empty() {
                return Err("COMPANION_BAD_SIGNATURE: the approval was not signed by the paired phone".into());
            }
            // The active key, or the first use of a pending pairing QR (which then becomes active).
            verify_approval(dir, id, &p.nonce, &device, sig)?;
            Ok(PollState::Approved { device, purpose: p.purpose })
        }
        Some("denied") => {
            forget(id);
            Ok(PollState::Denied)
        }
        Some("expired") => {
            forget(id);
            Ok(PollState::Expired)
        }
        _ => Ok(PollState::Pending),
    }
}

fn forget(id: &str) {
    if let Some(m) = PENDING.lock().unwrap_or_else(|p| p.into_inner()).as_mut() {
        m.remove(id);
    }
}

/// Phone side: sign an approval (after its own biometric check, done by the caller).
pub fn sign(dir: &Path, id: &str, nonce: &str, device: &str) -> Result<String, String> {
    let key = device_key(dir).ok_or("COMPANION_UNPAIRED: enter the pairing key from `gabagool-cli pair-companion` first")?;
    Ok(super::token::companion_sign(&key, id, nonce, device))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pairing_qr_round_trips_and_expires() {
        let key = "ab".repeat(32);
        let p = pair_payload(&key, 1_000.9, "DESK-1a2b");
        assert_eq!(p, format!("gbgpair1|{key}|1000|DESK-1a2b"));
        assert_eq!(parse_pair_input(&format!("  {p}\n"), 999.0).unwrap(), (key.clone(), Some("DESK-1a2b".to_string())));
        assert!(parse_pair_input(&p, 1_001.0).unwrap_err().starts_with("PAIR_QR_EXPIRED"));
        assert!(parse_pair_input("gbgpair1|abcd|soon|x", 0.0).unwrap_err().starts_with("PAIR_QR_BAD"));
        // The CLI's plain hex key still works.
        assert_eq!(parse_pair_input(&key, 5.0).unwrap(), (key, None));
    }

    /// Section 24: the desktop enforces the QR's TTL and single use. A QR key is pending until the
    /// phone's first valid approval within the TTL (then active, bound to that phone); unused past
    /// the TTL it is refused and the previous pairing stays; a second phone using the same payload
    /// is refused. The CLI pairing (no binding) accepts any device, as before.
    #[test]
    fn pairing_qr_is_pending_until_first_use_within_its_ttl() {
        let sign = |k: &[u8], dev: &str| super::super::token::companion_sign(k, "req1", "n1", dev);
        let old = vec![7u8; 32];
        let qr = PendingPair { key: vec![9u8; 32], expires_at: 1_120.0 };
        // Used within the TTL → promoted (the caller makes it active, bound to phone-A).
        assert_eq!(approval_verdict(Some(&old), None, Some(&qr), 1_060.0, "req1", "n1", "phone-A", &sign(&qr.key, "phone-A")), Ok(ApprovalKey::Promote));
        // …the old pairing keeps working until then.
        assert_eq!(approval_verdict(Some(&old), None, Some(&qr), 1_060.0, "req1", "n1", "phone-A", &sign(&old, "phone-A")), Ok(ApprovalKey::Active));
        // Expired and unused → refused; the old pairing is still the active one.
        let e = approval_verdict(Some(&old), None, Some(&qr), 1_121.0, "req1", "n1", "phone-A", &sign(&qr.key, "phone-A")).unwrap_err();
        assert!(e.starts_with("PAIR_QR_EXPIRED"), "{e}");
        assert_eq!(approval_verdict(Some(&old), None, Some(&qr), 1_121.0, "req1", "n1", "phone-A", &sign(&old, "phone-A")), Ok(ApprovalKey::Active));
        // After the first use: the QR key is active and bound to phone-A; a second use of the same
        // payload by another phone is refused (and no pending key is left to promote).
        assert_eq!(approval_verdict(Some(&qr.key), Some("phone-A"), None, 1_070.0, "req1", "n1", "phone-A", &sign(&qr.key, "phone-A")), Ok(ApprovalKey::Active));
        let e = approval_verdict(Some(&qr.key), Some("phone-A"), None, 1_070.0, "req1", "n1", "phone-B", &sign(&qr.key, "phone-B")).unwrap_err();
        assert!(e.starts_with("COMPANION_OTHER_DEVICE"), "{e}");
        // CLI pairing: no binding, any device; a bad signature is refused.
        assert_eq!(approval_verdict(Some(&old), None, None, 0.0, "req1", "n1", "phone-B", &sign(&old, "phone-B")), Ok(ApprovalKey::Active));
        let e = approval_verdict(Some(&old), None, None, 0.0, "req1", "n1", "phone-B", &sign(&[1u8; 32], "phone-B")).unwrap_err();
        assert!(e.starts_with("COMPANION_BAD_SIGNATURE"), "{e}");
        // First-ever pairing by QR (nothing active yet) works the same way.
        assert_eq!(approval_verdict(None, None, Some(&qr), 1_000.0, "req1", "n1", "phone-A", &sign(&qr.key, "phone-A")), Ok(ApprovalKey::Promote));
        // The in-memory pending key: valid within the TTL, discarded after it.
        let (hex, exp) = pair_begin_qr(5_000.0);
        assert_eq!(exp, 5_000.0 + PAIR_QR_TTL_S);
        assert_eq!(pending_pair(5_010.0).map(|p| super::super::hex(&p.key)), Some(hex));
        assert_eq!(pending_pair(exp + 1.0), None);
        assert_eq!(pending_pair(5_010.0), None, "an expired pending key is gone for good");
    }

    #[test]
    fn companion_counts_only_when_the_phone_polled_recently() {
        // Gateway up but the phone never polled (offline / no token): not a usable factor.
        assert!(!phone_recent(0.0, 1000.0));
        // Polled 5 s ago: usable.
        assert!(phone_recent(995.0, 1000.0));
        // Last poll older than the window: the phone is gone, the PIN fallback applies.
        assert!(!phone_recent(1000.0 - PHONE_SEEN_WITHIN_S - 1.0, 1000.0));
    }
}
