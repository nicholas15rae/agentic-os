//! Cross-device companion approval: the desktop (no biometrics) asks the paired phone to approve
//! an unlock with its fingerprint.
//!
//! 1. Desktop Rust posts `{id, nonce, device, purpose, expiresAt}` to the gateway mailbox
//!    (`POST /api/security/companion/request`, loopback only). The nonce never leaves Rust
//!    except to the gateway.
//! 2. The phone app polls `GET /api/security/companion/pending`, shows the request, runs its own
//!    biometric check (Rust, `tauri-plugin-biometric`) and signs
//!    `hmac(pairKey, "approve|id|nonce|deviceId")` → `POST /api/security/companion/respond`.
//! 3. Desktop Rust polls `GET /api/security/companion/result/{id}` and verifies the signature
//!    with ITS copy of the pairing key. The gateway is only a mailbox: it can't forge approval.
//!
//! The pairing key is generated by `gabagool-cli pair-companion` (desktop keychain) and entered
//! once on the phone (Settings → Security → companion pairing).

use std::collections::HashMap;
use std::path::Path;
use std::sync::Mutex;
use std::time::Duration;

const PAIR_ACCOUNT: &str = "companion-pair@security";
const PAIR_FILE: &str = "companion.key";
const DEVICE_ACCOUNT: &str = "companion-device@security";
const DEVICE_FILE: &str = "companion-device.key";

fn load_key(account: &str, dir: &Path, file: &str) -> Option<Vec<u8>> {
    let v = super::keychain(account).and_then(|e| e.get_password().ok()).or_else(|| std::fs::read_to_string(dir.join(file)).ok())?;
    super::unhex(v.trim()).filter(|k| k.len() >= 16)
}

fn store_key(account: &str, dir: &Path, file: &str, hexkey: &str) -> Result<&'static str, String> {
    if super::unhex(hexkey).is_none_or(|k| k.len() < 16) {
        return Err("the pairing key must be at least 32 hex characters".into());
    }
    if let Some(e) = super::keychain(account) {
        if e.set_password(hexkey).is_ok() && e.get_password().ok().as_deref() == Some(hexkey) {
            let _ = std::fs::remove_file(dir.join(file));
            return Ok("keychain");
        }
    }
    super::shared::write_atomic(&dir.join(file), hexkey.as_bytes()).map_err(|e| e.to_string())?;
    Ok("file")
}

/// Desktop side: the key that verifies phone approvals.
pub fn pair_key(dir: &Path) -> Option<Vec<u8>> {
    load_key(PAIR_ACCOUNT, dir, PAIR_FILE)
}

/// Generate a new pairing key on the desktop (CLI); returns it (hex) to enter on the phone.
pub fn pair_generate(dir: &Path) -> Result<String, String> {
    let k = super::token::random_hex(32);
    store_key(PAIR_ACCOUNT, dir, PAIR_FILE, &k)?;
    // Non-secret marker for the gateway (it can't read the keychain): "a phone is paired, queue
    // alerts for it".
    let _ = super::shared::write_atomic(&dir.join("companion.paired"), format!("{}
", super::now() as u64).as_bytes());
    Ok(k)
}

/// Phone side: the key it signs approvals with.
pub fn device_key(dir: &Path) -> Option<Vec<u8>> {
    load_key(DEVICE_ACCOUNT, dir, DEVICE_FILE)
}

pub fn device_store(dir: &Path, hexkey: &str) -> Result<&'static str, String> {
    store_key(DEVICE_ACCOUNT, dir, DEVICE_FILE, hexkey.trim())
}

#[derive(Clone, Debug)]
struct Pending {
    nonce: String,
    expires: f64,
    purpose: String,
    /// The matching number shown on the desktop; the phone's signature covers it.
    code: String,
}

/// A fresh 2-digit matching code (10–99). Pure given the random byte.
pub fn matching_code(byte: u8) -> String {
    format!("{}", 10 + (byte as u32 % 90))
}

/// Refuse a new request while another of the same kind (unlock / a step-up) is still waiting:
/// no stream of prompts to approve by mistake. Pure.
pub fn busy(pending: &[(String, f64)], purpose: &str, now: f64) -> bool {
    let unlock = |p: &str| !p.starts_with("step_up:");
    pending.iter().any(|(p, exp)| *exp > now && (p == purpose || (unlock(p) && unlock(purpose))))
}

static PENDING: Mutex<Option<HashMap<String, Pending>>> = Mutex::new(None);

fn client(timeout: Duration) -> Result<reqwest::Client, String> {
    reqwest::Client::builder().timeout(timeout).build().map_err(|e| e.to_string())
}

/// The phone polls the mailbox every 3 s while its app is open; older than this = not there.
pub const PHONE_SEEN_WITHIN_S: f64 = 30.0;

/// Can the companion path be used right now: enabled, paired, AND the phone itself checked the
/// gateway mailbox recently. The desktop reaching its own loopback gateway proves nothing about
/// the phone; counting that as "available" blocked the PIN-only fallback while the phone was
/// offline (PIN refused with SECOND_FACTOR_REQUIRED and no phone to approve: a deadlock).
pub async fn reachable(gateway: &str, dir: &Path, enabled: bool) -> bool {
    if !enabled || pair_key(dir).is_none() {
        return false;
    }
    let Ok(c) = client(Duration::from_millis(1500)) else { return false };
    let Ok(r) = c.get(format!("{}/api/security/state", gateway.trim_end_matches('/'))).send().await else { return false };
    if !r.status().is_success() {
        return false;
    }
    let seen = r.json::<serde_json::Value>().await.ok().and_then(|v| v.get("companionSeenAt").and_then(|x| x.as_f64())).unwrap_or(0.0);
    phone_recent(seen, super::now())
}

/// `seen` = the gateway's `companionSeenAt` (0 = never since it started).
pub fn phone_recent(seen: f64, now: f64) -> bool {
    seen > 0.0 && now - seen <= PHONE_SEEN_WITHIN_S
}

/// Post a new approval request; returns `(id, expiresAt)`.
pub async fn request(gateway: &str, dir: &Path, device: &str, purpose: &str, ttl: f64) -> Result<(String, f64, String), String> {
    if pair_key(dir).is_none() {
        return Err("COMPANION_UNPAIRED: run `gabagool-cli pair-companion` and enter the key on the phone".into());
    }
    {
        let g = PENDING.lock().unwrap_or_else(|p| p.into_inner());
        let waiting: Vec<(String, f64)> = g.as_ref().map(|m| m.values().map(|p| (p.purpose.clone(), p.expires)).collect()).unwrap_or_default();
        if busy(&waiting, purpose, super::now()) {
            return Err("COMPANION_BUSY: a phone approval is already waiting; answer it on the phone or let it expire".into());
        }
    }
    let code = matching_code(super::unhex(&super::token::random_hex(1)).and_then(|b| b.first().copied()).unwrap_or(42));
    let id = super::token::random_hex(12);
    let nonce = super::token::random_hex(16);
    let expires = super::now() + ttl;
    let body = serde_json::json!({ "id": id, "nonce": nonce, "device": device, "purpose": purpose, "expiresAt": expires });
    let r = client(Duration::from_secs(5))?
        .post(format!("{}/api/security/companion/request", gateway.trim_end_matches('/')))
        .json(&body)
        .send()
        .await
        .map_err(|_| "COMPANION_OFFLINE: the gateway mailbox is unreachable".to_string())?;
    if !r.status().is_success() {
        return Err(format!("COMPANION_OFFLINE: the gateway refused the request ({})", r.status()));
    }
    let mut g = PENDING.lock().unwrap_or_else(|p| p.into_inner());
    let m = g.get_or_insert_with(HashMap::new);
    let now = super::now();
    m.retain(|_, p| p.expires > now);
    m.insert(id.clone(), Pending { nonce, expires, purpose: purpose.to_string(), code: code.clone() });
    Ok((id, expires, code))
}

#[derive(Debug, PartialEq)]
pub enum PollState {
    Pending,
    /// `purpose` is what this process asked for ("unlock", "idle", "step_up:trading", ...).
    Approved { device: String, purpose: String },
    Denied,
    Expired,
}

/// The verdict on a request this process created (signature checked here).
pub async fn poll(gateway: &str, dir: &Path, id: &str) -> Result<PollState, String> {
    let pending = {
        let g = PENDING.lock().unwrap_or_else(|p| p.into_inner());
        g.as_ref().and_then(|m| m.get(id).cloned())
    };
    let Some(p) = pending else { return Ok(PollState::Expired) };
    if super::now() > p.expires {
        forget(id);
        return Ok(PollState::Expired);
    }
    let r = client(Duration::from_secs(5))?
        .get(format!("{}/api/security/companion/result/{}", gateway.trim_end_matches('/'), id))
        .send()
        .await
        .map_err(|_| "COMPANION_OFFLINE: the gateway mailbox is unreachable".to_string())?;
    let v: serde_json::Value = r.json().await.map_err(|e| e.to_string())?;
    match v["state"].as_str() {
        Some("approved") => {
            let device = v["deviceId"].as_str().unwrap_or("").to_string();
            let sig = v["sig"].as_str().unwrap_or("");
            let key = pair_key(dir).ok_or("COMPANION_UNPAIRED: no pairing key")?;
            forget(id);
            if device.is_empty() || !super::token::companion_verify(&key, id, &p.nonce, &device, &p.code, sig) {
                return Err("COMPANION_BAD_SIGNATURE: the approval was not signed by the paired phone".into());
            }
            Ok(PollState::Approved { device, purpose: p.purpose })
        }
        Some("denied") => {
            forget(id);
            Ok(PollState::Denied)
        }
        Some("expired") => {
            forget(id);
            Ok(PollState::Expired)
        }
        _ => Ok(PollState::Pending),
    }
}

fn forget(id: &str) {
    if let Some(m) = PENDING.lock().unwrap_or_else(|p| p.into_inner()).as_mut() {
        m.remove(id);
    }
}

/// Phone side: sign an approval (after its own biometric check, done by the caller).
pub fn sign(dir: &Path, id: &str, nonce: &str, device: &str, code: &str) -> Result<String, String> {
    let key = device_key(dir).ok_or("COMPANION_UNPAIRED: enter the pairing key from `gabagool-cli pair-companion` first")?;
    Ok(super::token::companion_sign(&key, id, nonce, device, code))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matching_codes_are_two_digits_and_one_request_waits_at_a_time() {
        for b in [0u8, 1, 89, 90, 255] {
            let c = matching_code(b);
            assert_eq!(c.len(), 2, "{c}");
        }
        let now = 100.0;
        let waiting = vec![("unlock".to_string(), 150.0)];
        assert!(busy(&waiting, "idle", now), "a second unlock prompt waits");
        assert!(!busy(&waiting, "step_up:trading", now), "a step-up is its own lane");
        assert!(!busy(&[("unlock".into(), 90.0)], "unlock", now), "an expired one doesn't count");
        assert!(busy(&[("step_up:trading".into(), 150.0)], "step_up:trading", now));
    }

    #[test]
    fn companion_counts_only_when_the_phone_polled_recently() {
        // Gateway up but the phone never polled (offline / no token): not a usable factor.
        assert!(!phone_recent(0.0, 1000.0));
        // Polled 5 s ago: usable.
        assert!(phone_recent(995.0, 1000.0));
        // Last poll older than the window: the phone is gone, the PIN fallback applies.
        assert!(!phone_recent(1000.0 - PHONE_SEEN_WITHIN_S - 1.0, 1000.0));
    }
}
